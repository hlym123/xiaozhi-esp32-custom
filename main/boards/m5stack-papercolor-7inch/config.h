#ifndef _BOARD_CONFIG_H_
#define _BOARD_CONFIG_H_

#include <driver/gpio.h>

#define AUDIO_INPUT_SAMPLE_RATE  24000
#define AUDIO_OUTPUT_SAMPLE_RATE 24000

// ES8311 I2S0
#define AUDIO_I2S_GPIO_MCLK GPIO_NUM_42
#define AUDIO_I2S_GPIO_BCLK GPIO_NUM_41
#define AUDIO_I2S_GPIO_WS   GPIO_NUM_39
#define AUDIO_I2S_GPIO_DOUT GPIO_NUM_38
#define AUDIO_I2S_GPIO_DIN  GPIO_NUM_40

// System I2C0 and ES8311
#define AUDIO_CODEC_I2C_SDA_PIN GPIO_NUM_1
#define AUDIO_CODEC_I2C_SCL_PIN GPIO_NUM_2
// esp_codec_dev expects the ES8311 8-bit I2C address.
#define AUDIO_CODEC_ES8311_ADDR (0x18 << 1)
#define AUDIO_CODEC_GPIO_PA     GPIO_NUM_45

// M5PM1 controls the codec power rail through GPIO4.
#define PMIC_I2C_ADDR          0x6E
#define PMIC_CODEC_POWER_GPIO M5PM1_GPIO_NUM_4

#define KEY1_GPIO GPIO_NUM_3
#define KEY2_GPIO GPIO_NUM_9

#define BUILTIN_LED_GPIO GPIO_NUM_NC

#endif // _BOARD_CONFIG_H_
